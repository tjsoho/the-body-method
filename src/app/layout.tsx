import { Lora, Hanken_Grotesk } from "next/font/google";
import "./globals.css";
import HeaderWrapper from "@/components/core/HeaderWrapper";
import Footer from "@/components/core/Footer";
import { Toaster } from "react-hot-toast";
import StructuredData from "@/components/core/StructuredData";
import { organizationSchema, websiteSchema } from "@/utils/schema";
import { siteConfig } from "@/config/site";

const lora = Lora({
    subsets: ["latin"],
    weight: ["400", "500"],
    style: ["normal", "italic"],
    variable: "--font-lora",
    display: "swap",
});

const hanken = Hanken_Grotesk({
    subsets: ["latin"],
    weight: ["400", "500", "600"],
    variable: "--font-hanken",
    display: "swap",
});

// Per-page meta (title, description, OG, canonical) is generated by each
// route's generateMetadata() via buildPageMetadata. The root layout only
// emits site-wide JSON-LD (Organization + WebSite) so Google Rich Results
// and LLM crawlers have a stable identity for the publisher.

export default function RootLayout({
    children,
}: Readonly<{
    children: React.ReactNode;
}>) {
    const htmlLang = siteConfig.locale.split("-")[0] || "en";
    return (
        <html lang={htmlLang} className={`${lora.variable} ${hanken.variable}`}>
            <body className="antialiased">
                <StructuredData
                    data={[organizationSchema(), websiteSchema()]}
                />
                <Toaster
                    position="top-right"
                    toastOptions={{
                        duration: 3000,
                        style: {
                            background: "#1b2518",
                            color: "#f4f2ed",
                            border: "1px solid rgba(244,242,237,.2)",
                        },
                    }}
                />
                <HeaderWrapper />
                <main>{children}</main>
                <Footer />
            </body>
        </html>
    );
}
